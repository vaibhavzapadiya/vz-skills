// Generates src/docs/content/changelog.mdx from the repository's CHANGELOG.md so the page cannot drift.
// Usage: node scripts/sync-changelog.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'CHANGELOG.md');
const out = join(here, '..', 'src', 'docs', 'content', 'changelog.mdx');

/** Escape characters MDX would treat as JSX/expressions, leaving inline code and fenced code alone. */
function escapeLine(line) {
  return line
    .split(/(`[^`]*`)/g)
    .map((part) => (part.startsWith('`') && part.endsWith('`') && part.length > 1 ? part : part.replace(/</g, '&lt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')))
    .join('');
}

export function build() {
  const raw = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
  const lines = raw.split('\n');
  const body = [];
  let fenced = false;
  let intro = true;
  for (const line of lines) {
    if (line.startsWith('```')) fenced = !fenced;
    if (!fenced && /^# /.test(line)) continue; // page title comes from the registry
    if (!fenced && intro && /^## /.test(line)) intro = false;
    body.push(fenced ? line : escapeLine(line));
  }
  const text = body.join('\n').replace(/^\s*\n/, '');
  return `{/* Generated by scripts/sync-changelog.mjs from CHANGELOG.md. Do not edit by hand. */}\n\n${text.trimEnd()}\n`;
}

const next = build();
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== next) {
    console.error('changelog.mdx is stale; run: node scripts/sync-changelog.mjs');
    process.exit(1);
  }
  console.log('changelog.mdx is up to date');
} else {
  writeFileSync(out, next);
  console.log('wrote', out);
}
