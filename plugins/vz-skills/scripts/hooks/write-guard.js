#!/usr/bin/env node
'use strict';
/**
 * PreToolUse guard for Write / Edit / MultiEdit / NotebookEdit.
 *
 * Decisions:
 *   deny - writes into .git/ internals, SSH/cloud credential stores, or OS system directories
 *   ask  - writes outside the project root; to secret-bearing files (.env, *.pem, *.key, ...);
 *          to local agent instructions (CLAUDE.md, .claude/*, AGENTS.md) or VZ config;
 *          to lockfiles; to configured protected_paths; or content that looks like a credential
 *   (none) - everything else
 *
 * Advisory, fail-open. Not a security boundary. See docs/hooks.md.
 */
const path = require('node:path');
const os = require('node:os');
const { readStdin, failOpen, emit, preToolDecision, projectRootFrom, loadConfig, globToRegExp, toPosix, relativeToRoot } = require('../lib/hookio');

const SECRET_CONTENT = /(AKIA[0-9A-Z]{16}|ghp_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}|xox[baprs]-[A-Za-z0-9-]{20,}|sk-(proj-|ant-)?[A-Za-z0-9_-]{30,}|-----BEGIN (RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY-----|AIza[0-9A-Za-z_-]{30,}|(password|passwd|secret|api[_-]?key|token)\s*[:=]\s*["'][^"'\s]{16,}["'])/i;
const PLACEHOLDER = /(example|placeholder|changeme|your[_-]?(key|token|secret)|xxxx|<[^>]+>|\$\{[^}]+\}|process\.env|os\.environ|dummy|fake|test[_-]?(key|token))/i;

function main() {
  const { data, error } = readStdin();
  if (error) return failOpen(error);
  if (data.hook_event_name && data.hook_event_name !== 'PreToolUse') return failOpen(`unexpected event ${data.hook_event_name}`);
  const ti = data.tool_input || {};
  const file = typeof ti.file_path === 'string' ? ti.file_path : typeof ti.notebook_path === 'string' ? ti.notebook_path : null;
  if (!file) return failOpen('no tool_input.file_path');
  const root = projectRootFrom(data);
  const cfg = loadConfig(root);
  const hooks = cfg ? cfg.effective.hooks : { write_guard: 'on', protected_paths: [] };
  if (hooks.write_guard === 'off') return process.exit(0);

  const { abs, rel, outside } = relativeToRoot(root, file);
  const p = toPosix(abs).toLowerCase();
  const home = toPosix(os.homedir()).toLowerCase();
  const base = path.basename(p);

  // deny
  if (/(^|\/)\.git\/(?!hooks\/|info\/exclude)/.test(toPosix(rel)) || /\/\.git\/(objects|refs|hooks|index|config|head)/.test(p)) return emit(preToolDecision('deny', 'vz-skills write guard: writing inside .git/ internals is refused; use git commands instead.'));
  if (p.startsWith(home + '/.ssh/') || p.startsWith(home + '/.aws/') || p.startsWith(home + '/.gnupg/') || p.startsWith(home + '/.kube/') || p === home + '/.netrc' || p === home + '/.npmrc' || p === home + '/.pypirc') return emit(preToolDecision('deny', 'vz-skills write guard: refusing to write a credential store in the home directory.'));
  if (/^\/(etc|usr|bin|sbin|boot|lib|lib64|sys|proc|dev)\//.test(p) || /^[a-z]:\/(windows|program files|program files \(x86\)|programdata)\//.test(p)) return emit(preToolDecision('deny', 'vz-skills write guard: refusing to write into an operating-system directory.'));
  if (p.startsWith(home + '/.claude/') && /settings(\.local)?\.json$|\.claude\.json$/.test(p)) return emit(preToolDecision('deny', 'vz-skills write guard: Claude Code user settings are the user\'s to edit; refusing to modify them from a hook-guarded write.'));

  // ask
  const reasons = [];
  if (outside) reasons.push(`path is outside the project root (${root})`);
  if (/^\.env(\..+)?$/.test(base) && !/\.(example|sample|template|dist)$/.test(base)) reasons.push('.env files hold secrets');
  if (/\.(pem|key|p12|pfx|jks|keystore|crt|cer)$/.test(base) || /^id_(rsa|ed25519|ecdsa|dsa)(\.pub)?$/.test(base) || /(^|\/)(secrets?|credentials?)\.(json|ya?ml|toml|txt|env)$/.test(p)) reasons.push('file name suggests credentials');
  if (/(^|\/)(claude\.md|claude\.local\.md|agents\.md|gemini\.md|\.cursorrules)$/.test(p) || /(^|\/)\.claude\/(settings(\.local)?\.json|rules\/[^/]+\.md|claude\.md)$/.test(p)) reasons.push('modifies local agent instructions or settings; confirm the user wants that');
  if (/(^|\/)\.vz-skills\/config\.json$/.test(p)) reasons.push('modifies the VZ Skills safety/rigor configuration');
  if (/^(package-lock\.json|npm-shrinkwrap\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|poetry\.lock|uv\.lock|pipfile\.lock|cargo\.lock|go\.sum|gemfile\.lock|composer\.lock|packages\.lock\.json)$/.test(base)) reasons.push('lockfiles should be regenerated by the package manager, not hand-edited');
  for (const g of hooks.protected_paths || []) { if (globToRegExp(g).test(toPosix(rel))) { reasons.push(`matches protected path "${g}" from .vz-skills/config.json`); break; } }
  const content = [ti.content, ti.new_string, ti.new_source, ...(Array.isArray(ti.edits) ? ti.edits.map((e) => e && e.new_string) : [])].filter((s) => typeof s === 'string').join('\n');
  if (content && SECRET_CONTENT.test(content)) {
    const m = content.match(SECRET_CONTENT)[0];
    if (!PLACEHOLDER.test(m) && !/\.(example|sample|template|dist)$/.test(base) && !/(fixture|test|spec|mock)/i.test(p)) reasons.push('content contains a credential-looking value; secrets must not be written into the repository');
  }
  if (!reasons.length) return process.exit(0);
  return emit(preToolDecision('ask', `vz-skills write guard: ${reasons.join('; ')}. Confirm with the user before writing.`));
}

try { main(); } catch (e) { failOpen(`internal error: ${e.message}`); }
